//! Layout spacing values measured in logical pixels.

/// Hairline separation for tightly grouped details.
pub const XXS: f32 = 2.0;
/// Compact separation for closely related content.
pub const XS: f32 = 4.0;
/// Standard separation within a control or compact group.
pub const SM: f32 = 8.0;
/// Comfortable separation between related controls.
pub const MD: f32 = 12.0;
/// Standard inset and separation for grouped content.
pub const LG: f32 = 16.0;
/// Broad separation between sections.
pub const XL: f32 = 24.0;
/// Major separation between distinct regions.
pub const XXL: f32 = 32.0;
